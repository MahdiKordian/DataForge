"""Save a fitted pipeline as one JSON file and run it again later. JSON only, never pickle."""
from __future__ import annotations

import json
import pprint
import platform
from datetime import datetime

import numpy as np
import pandas as pd

from .contract import infer_contract
from .pipeline import Pipeline, _dec, _enc
from .splitting import balance_train, split_frame

FORMAT, VERSION = "dataforge-pipeline", 1


class SpecError(ValueError):
    """The pipeline file is not valid."""


def make_spec(pipeline: Pipeline, cfg: dict, split_info: dict, raw_train: pd.DataFrame, name: str = "pipeline") -> dict:
    return {
        "format": FORMAT, "version": VERSION, "name": name, "created": datetime.now().isoformat(timespec="seconds"),
        "target": pipeline.target,
        "split": {k: split_info.get(k) for k in ("test_pct", "val_pct", "seed", "balance", "stratify")},
        "steps": _enc(cfg),
        "pipeline_state": pipeline.state(),
        "input_contract": infer_contract(raw_train.drop(columns=[pipeline.target], errors="ignore")),
        "environment": {"python": platform.python_version(), "pandas": pd.__version__, "numpy": np.__version__},
    }


def dumps(spec: dict) -> str:
    return json.dumps(spec, indent=2, default=str)


MAX_SPEC_MB = 50


def loads(text) -> dict:
    if len(text) > MAX_SPEC_MB * 1048576:
        raise SpecError(f"The pipeline file is larger than {MAX_SPEC_MB} MB.")
    try:
        spec = json.loads(text)
    except (json.JSONDecodeError, TypeError) as e:
        raise SpecError(f"This is not a JSON file: {e}") from None
    if not isinstance(spec, dict) or spec.get("format") != FORMAT:
        raise SpecError("This file is not a DataForge pipeline.")
    if spec.get("version") != VERSION:
        raise SpecError(f"Unsupported pipeline version {spec.get('version')}.")
    for k in ("pipeline_state", "steps", "split"):
        if k not in spec:
            raise SpecError(f"The pipeline file is missing '{k}'.")
    return spec


def apply_saved(spec: dict, df: pd.DataFrame):
    """Apply the saved, already-fitted pipeline to new data. Returns (frame, warnings)."""
    pipe = Pipeline.from_state(spec["pipeline_state"])
    out = pipe.transform(df)
    return out, pipe.warnings_


def refit(spec: dict, df: pd.DataFrame):
    """Run the saved settings from scratch on a dataset: split, fit on train, transform the rest."""
    from .pipeline import build_pipeline
    s, t = spec["split"], spec["target"]
    train, val, test, _ = split_frame(df, t, s["test_pct"], s["val_pct"], s["seed"], bool(s.get("stratify", True)))
    pipe = build_pipeline(_dec(spec["steps"]), t)
    tr = pipe.fit_transform(train)
    va = pipe.transform(val) if val is not None else None
    te = pipe.transform(test)
    return {"train": balance_train(tr, t, s.get("balance") or "None", s["seed"]), "val": va, "test": te, "pipeline": pipe}


def to_script(spec: dict, data_file: str = "your_data.csv") -> str:
    s, steps = spec["split"], _dec(spec["steps"])
    return f'''"""Generated by DataForge on {spec["created"]}. Reproduces the preparation of '{spec["name"]}'.
Needs the dataforge-engine package (pip install dataforge-engine)."""
import pandas as pd
from dataforge_engine import build_pipeline, split_frame, balance_train

TARGET = {spec["target"]!r}
STEPS = {pprint.pformat(steps, width=100, sort_dicts=False)}

df = pd.read_csv({data_file!r})
train, val, test, _ = split_frame(df, TARGET, {s["test_pct"]}, {s["val_pct"]}, {s["seed"]}, {bool(s.get("stratify", True))})
pipe = build_pipeline(STEPS, TARGET)
train = pipe.fit_transform(train)               # everything is learned from the training set only
val = pipe.transform(val) if val is not None else None
test = pipe.transform(test)
train = balance_train(train, TARGET, {s.get("balance") or "None"!r}, {s["seed"]})

train.to_csv("train_prepared.csv", index=False)
test.to_csv("test_prepared.csv", index=False)
if val is not None:
    val.to_csv("val_prepared.csv", index=False)
'''
